#!/bin/sh
set -e

# Στήνει ή ενημερώνει τους πίνακες πριν σηκωθεί η εφαρμογή.
#
# Σε λειτουργία παραγωγής το Payload δεν αλλάζει μόνο του το σχήμα της
# βάσης — και σωστά, γιατί μια αυτόματη αλλαγή θα μπορούσε να σβήσει
# δεδομένα. Τα migrations περιγράφουν ρητά τι αλλάζει και τρέχουν εδώ, σε
# κάθε εκκίνηση. Όσα έχουν ήδη εφαρμοστεί παραλείπονται.
echo "→ Έλεγχος migrations..."
npm run payload -- migrate

echo "→ Εκκίνηση εφαρμογής..."
exec npm run start
